package enum PasteboardTransactionMarker {
    /// Marks the temporary value of one paste transaction. It is still on the
    /// clipboard at launch only when Speaker ended before restoring.
    package static let type = NSPasteboard.PasteboardType(
        "com.local.speaker.paste-session"
    )
    /// Marks a value the user explicitly copied. It proves ownership while
    /// the copy is verified and then stays like any other copy.
    package static let copyType = NSPasteboard.PasteboardType(
        "com.local.speaker.copy"
    )
}

/// The nspasteboard.org markers that clipboard managers honor.
package enum PasteboardPrivacyType {
    /// The value stays on the clipboard only briefly: do not record it.
    package static let transient = NSPasteboard.PasteboardType(
        "org.nspasteboard.TransientType"
    )
    /// Software wrote the value; the user did not copy it.
    package static let autoGenerated = NSPasteboard.PasteboardType(
        "org.nspasteboard.AutoGeneratedType"
    )
    /// The value is sensitive: do not record or display it.
    package static let concealed = NSPasteboard.PasteboardType(
        "org.nspasteboard.ConcealedType"
    )
}

/// What one Speaker clipboard write is for. It decides the ownership marker
/// and how clipboard managers and Universal Clipboard treat the value.
package enum PasteboardWritePurpose: Equatable, Sendable {
    /// The value Command-V pastes; the prior clipboard returns right after.
    case pasteTransaction
    /// A value the user asked to copy, kept like an ordinary copy.
    case explicitCopy
    /// A user-requested copy of a secure Input Target's result.
    case concealedCopy

    package var markerType: NSPasteboard.PasteboardType {
        switch self {
        case .pasteTransaction: PasteboardTransactionMarker.type
        case .explicitCopy, .concealedCopy: PasteboardTransactionMarker.copyType
        }
    }

    /// Empty representations written beside the text.
    package var privacyTypes: [NSPasteboard.PasteboardType] {
        switch self {
        case .pasteTransaction:
            [PasteboardPrivacyType.transient, PasteboardPrivacyType.autoGenerated]
        case .explicitCopy:
            []
        case .concealedCopy:
            [PasteboardPrivacyType.concealed]
        }
    }

    /// Keeps the value off Universal Clipboard.
    package var isCurrentHostOnly: Bool {
        switch self {
        case .pasteTransaction, .concealedCopy: true
        case .explicitCopy: false
        }
    }
}

/// Clears the value of a paste transaction that Speaker never restored
/// because it crashed or was force-quit inside the restore window.
package enum AbandonedPasteTransaction {
    @MainActor
    @discardableResult
    package static func clear(
        from pasteboard: ClipboardPasteboardAccess = .live
    ) -> Bool {
        let changeCount = pasteboard.changeCount()
        guard pasteboard.readMarker(.pasteTransaction) != nil,
            pasteboard.changeCount() == changeCount
        else { return false }
        _ = pasteboard.clearContents(false)
        return true
    }
}

/// Bounds data retained by Speaker for rollback. AppKit exposes each
/// representation only as a complete `Data` value, so one value may be
/// materialized by the system before its size can be checked.
package struct PasteboardSnapshotBudget: Equatable, Sendable {
    package let maximumItemCount: Int
    package let maximumRepresentationCount: Int
    package let maximumBytesPerRepresentation: Int
    package let maximumTotalBytes: Int

    package init(
        maximumItemCount: Int,
        maximumRepresentationCount: Int,
        maximumBytesPerRepresentation: Int,
        maximumTotalBytes: Int
    ) {
        precondition(maximumItemCount >= 0)
        precondition(maximumRepresentationCount >= 0)
        precondition(maximumBytesPerRepresentation >= 0)
        precondition(maximumTotalBytes >= 0)
        self.maximumItemCount = maximumItemCount
        self.maximumRepresentationCount = maximumRepresentationCount
        self.maximumBytesPerRepresentation = maximumBytesPerRepresentation
        self.maximumTotalBytes = maximumTotalBytes
    }

    package static let standard = Self(
        maximumItemCount: 64,
        maximumRepresentationCount: 256,
        maximumBytesPerRepresentation: 16 * 1_024 * 1_024,
        maximumTotalBytes: 32 * 1_024 * 1_024
    )
}

package struct PasteboardSnapshot: Equatable, Sendable {
    package let items: [[String: Data]]
    fileprivate let changeCount: Int

    @MainActor
    package static func capture(
        from pasteboard: ClipboardPasteboardAccess,
        budget: PasteboardSnapshotBudget
    ) -> Self? {
        let capturedChangeCount = pasteboard.changeCount()
        guard let itemCount = pasteboard.itemCount(),
            itemCount >= 0,
            itemCount <= budget.maximumItemCount
        else { return nil }

        var representationCount = 0
        var totalBytes = 0
        var items: [[String: Data]] = []
        items.reserveCapacity(itemCount)

        for itemIndex in 0..<itemCount {
            guard let types = pasteboard.itemTypes(itemIndex) else {
                return nil
            }
            guard
                types.count
                    <= budget.maximumRepresentationCount - representationCount
            else { return nil }
            representationCount += types.count

            var representations: [String: Data] = [:]
            representations.reserveCapacity(types.count)
            for type in types {
                guard representations[type] == nil,
                    let data = pasteboard.data(itemIndex, type),
                    data.count <= budget.maximumBytesPerRepresentation,
                    data.count <= budget.maximumTotalBytes - totalBytes
                else { return nil }
                representations[type] = data
                totalBytes += data.count
            }
            items.append(representations)
        }

        guard pasteboard.changeCount() == capturedChangeCount else { return nil }
        return Self(items: items, changeCount: capturedChangeCount)
    }
}

package struct PasteboardReplacementTransaction: Sendable {
    private let snapshot: PasteboardSnapshot
    private let marker: String
    private let purpose: PasteboardWritePurpose
    private let ownedChangeCount: Int
    private let pasteboard: ClipboardPasteboardAccess

    @MainActor
    package static func prepare(
        text: String,
        purpose: PasteboardWritePurpose,
        pasteboard: ClipboardPasteboardAccess,
        budget: PasteboardSnapshotBudget = .standard
    ) -> Self? {
        guard
            let snapshot = PasteboardSnapshot.capture(
                from: pasteboard,
                budget: budget
            ), pasteboard.changeCount() == snapshot.changeCount
        else { return nil }

        let marker = UUID().uuidString
        let clearedChangeCount = pasteboard.clearContents(purpose.isCurrentHostOnly)
        guard pasteboard.writeText(text, marker, purpose) else {
            if pasteboard.changeCount() == clearedChangeCount
                || pasteboard.readMarker(purpose) == marker
            {
                _ = restore(snapshot, to: pasteboard)
            }
            return nil
        }
        return Self(
            snapshot: snapshot,
            marker: marker,
            purpose: purpose,
            ownedChangeCount: pasteboard.changeCount(),
            pasteboard: pasteboard
        )
    }

    @MainActor
    package func verifies(_ text: String) -> Bool {
        stillOwnsPasteboard() && pasteboard.readString() == text
    }

    @MainActor
    @discardableResult
    package func restoreIfOwned() -> Bool {
        guard stillOwnsPasteboard() else { return false }
        return Self.restore(snapshot, to: pasteboard)
    }

    @MainActor
    package func stillOwnsPasteboard() -> Bool {
        PasteboardTransactionOwnership.ownsPasteboard(
            currentChangeCount: pasteboard.changeCount(),
            currentMarker: pasteboard.readMarker(purpose),
            ownedChangeCount: ownedChangeCount,
            marker: marker
        )
    }

    @MainActor
    private static func restore(
        _ snapshot: PasteboardSnapshot,
        to pasteboard: ClipboardPasteboardAccess
    ) -> Bool {
        _ = pasteboard.clearContents(false)
        return snapshot.items.isEmpty || pasteboard.writeItems(snapshot.items)
    }
}

private enum PasteboardTransactionOwnership {
    static func ownsPasteboard(
        currentChangeCount: Int,
        currentMarker: String?,
        ownedChangeCount: Int,
        marker: String
    ) -> Bool {
        currentChangeCount == ownedChangeCount && currentMarker == marker
    }
}

package struct PasteCommandEventPlan: Sendable {
    package enum Transition: Equatable, Sendable {
        case commandDown
        case vDown
        case vUp
        case commandUp
    }

    package let sourceStateID: CGEventSourceStateID
    package let transitions: [Transition]

    package struct KeyEvent: Equatable, Sendable {
        package let keyCode: CGKeyCode
        package let keyDown: Bool
        package let isCommandHeld: Bool
    }

    package static let standard = Self(
        sourceStateID: .combinedSessionState,
        transitions: [
            .commandDown,
            .vDown,
            .vUp,
            .commandUp,
        ]
    )

    /// The key events for the transitions, with V on `vKeyCode`.
    package func keyEvents(vKeyCode: CGKeyCode) -> [KeyEvent] {
        transitions.map { transition in
            switch transition {
            case .commandDown:
                KeyEvent(keyCode: CGKeyCode(kVK_Command), keyDown: true, isCommandHeld: true)
            case .vDown:
                KeyEvent(keyCode: vKeyCode, keyDown: true, isCommandHeld: true)
            case .vUp:
                KeyEvent(keyCode: vKeyCode, keyDown: false, isCommandHeld: true)
            case .commandUp:
                KeyEvent(keyCode: CGKeyCode(kVK_Command), keyDown: false, isCommandHeld: false)
            }
        }
    }
}

/// Finds the virtual key that types "v" while Command is held, so the target
/// receives Command-V under Dvorak, AZERTY, or "Dvorak - QWERTY ⌘" too.
package struct PasteKeyCodeLookup: Sendable {
    private let lookup: @MainActor @Sendable () -> CGKeyCode?

    package init(lookup: @escaping @MainActor @Sendable () -> CGKeyCode?) {
        self.lookup = lookup
    }

    /// Falls back to the ANSI V position when the layout yields no "v".
    @MainActor
    package func vKeyCode() -> CGKeyCode {
        lookup() ?? CGKeyCode(kVK_ANSI_V)
    }

    package static let currentKeyboardLayout = Self {
        KeyboardLayoutKeyCodes.currentLayoutKeyCode(producing: "v")
    }
}

/// Text Input Sources must be read on the main thread.
package enum KeyboardLayoutKeyCodes {
    /// The keyboard layout in use, which is the layout under an input method
    /// such as Pinyin rather than the input method itself.
    @MainActor
    package static func currentLayoutKeyCode(producing character: String) -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue()
        else { return nil }
        return keyCode(producing: character, in: source)
    }

    /// An installed layout by input source ID, such as
    /// `com.apple.keylayout.Dvorak`.
    @MainActor
    package static func keyCode(
        producing character: String,
        inLayoutWithID inputSourceID: String
    ) -> CGKeyCode? {
        let filter = [kTISPropertyInputSourceID as String: inputSourceID] as CFDictionary
        guard
            let sources = TISCreateInputSourceList(filter, true)?.takeRetainedValue()
                as? [TISInputSource],
            let source = sources.first
        else { return nil }
        return keyCode(producing: character, in: source)
    }

    @MainActor
    private static func keyCode(
        producing character: String,
        in source: TISInputSource
    ) -> CGKeyCode? {
        guard let property = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { return nil }
        let layoutData = Unmanaged<CFData>.fromOpaque(property).takeUnretainedValue() as Data
        let commandModifierState = UInt32((cmdKey >> 8) & 0xFF)
        let keyboardType = UInt32(LMGetKbdType())
        let candidates = [UInt16(kVK_ANSI_V)] + (0..<128).map(UInt16.init)
        return layoutData.withUnsafeBytes { bytes -> CGKeyCode? in
            guard let layout = bytes.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self)
            else { return nil }
            for keyCode in candidates {
                var deadKeyState: UInt32 = 0
                var length = 0
                var characters = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(
                    layout,
                    keyCode,
                    UInt16(kUCKeyActionDown),
                    commandModifierState,
                    keyboardType,
                    OptionBits(kUCKeyTranslateNoDeadKeysMask),
                    &deadKeyState,
                    characters.count,
                    &length,
                    &characters
                )
                guard status == noErr, length > 0 else { continue }
                if String(utf16CodeUnits: characters, count: length).lowercased() == character {
                    return CGKeyCode(keyCode)
                }
            }
            return nil
        }
    }
}

package struct PasteboardDeliveryTransaction: Sendable {
    private let replacement: PasteboardReplacementTransaction
    private let conditionalRestoreDelay: Duration
    private let sleepBeforeRestore: @Sendable (Duration) async throws -> Void
    private let conditionalRestoreDidFinish: @Sendable () async -> Void

    package static func prepare(
        text: String,
        pasteboard: ClipboardPasteboardAccess = .live,
        snapshotBudget: PasteboardSnapshotBudget = .standard,
        conditionalRestoreDelay: Duration = .milliseconds(500),
        sleepBeforeRestore:
            @escaping @Sendable (Duration) async throws -> Void = { duration in
                try await Task.sleep(for: duration)
            },
        conditionalRestoreDidFinish:
            @escaping @Sendable () async -> Void = {}
    ) async -> Self? {
        await MainActor.run {
            guard
                let replacement = PasteboardReplacementTransaction.prepare(
                    text: text,
                    purpose: .pasteTransaction,
                    pasteboard: pasteboard,
                    budget: snapshotBudget
                )
            else { return nil }
            guard replacement.verifies(text) else {
                replacement.restoreIfOwned()
                return nil
            }
            return Self(
                replacement: replacement,
                conditionalRestoreDelay: conditionalRestoreDelay,
                sleepBeforeRestore: sleepBeforeRestore,
                conditionalRestoreDidFinish: conditionalRestoreDidFinish
            )
        }
    }

    package static func ownsPasteboard(
        currentChangeCount: Int,
        currentMarker: String?,
        ownedChangeCount: Int,
        marker: String
    ) -> Bool {
        PasteboardTransactionOwnership.ownsPasteboard(
            currentChangeCount: currentChangeCount,
            currentMarker: currentMarker,
            ownedChangeCount: ownedChangeCount,
            marker: marker
        )
    }

    package func restoreIfOwned() async {
        _ = await MainActor.run {
            replacement.restoreIfOwned()
        }
    }

    package func stillOwnsPasteboard() async -> Bool {
        await MainActor.run {
            replacement.stillOwnsPasteboard()
        }
    }

    package func restoreAfterDelay() async {
        do {
            try await sleepBeforeRestore(conditionalRestoreDelay)
        } catch {
            return
        }
        await restoreIfOwned()
        await conditionalRestoreDidFinish()
    }

    package static func postCommandV(
        keyCodeLookup: PasteKeyCodeLookup = .currentKeyboardLayout
    ) async -> Bool {
        let plan = PasteCommandEventPlan.standard
        let vKeyCode = await keyCodeLookup.vKeyCode()
        guard let source = CGEventSource(stateID: plan.sourceStateID) else {
            return false
        }
        let events = plan.keyEvents(vKeyCode: vKeyCode).compactMap { keyEvent -> CGEvent? in
            guard
                let event = CGEvent(
                    keyboardEventSource: source,
                    virtualKey: keyEvent.keyCode,
                    keyDown: keyEvent.keyDown
                )
            else { return nil }
            event.flags = keyEvent.isCommandHeld ? .maskCommand : []
            return event
        }
        guard events.count == plan.transitions.count else { return false }

        for (index, event) in events.enumerated() {
            event.post(tap: .cghidEventTap)
            if index < events.index(before: events.endIndex) {
                try? await Task.sleep(for: .milliseconds(10))
            }
        }
        return true
    }
}

package actor PasteboardRestoreCoordinator {
    private var acceptsTransactions = true
    private var active: Set<UUID> = []
    private var pending: [UUID: Task<Void, Never>] = [:]
    private var shutdownWaiters: [CheckedContinuation<Void, Never>] = []

    package init() {}

    package func reserve() -> UUID? {
        guard acceptsTransactions else { return nil }
        let id = UUID()
        active.insert(id)
        return id
    }

    package func schedule(
        _ transaction: PasteboardDeliveryTransaction,
        reservation id: UUID
    ) {
        precondition(active.contains(id))
        pending[id] = Task { [weak self] in
            await transaction.restoreAfterDelay()
            await self?.didFinish(id)
        }
    }

    package func abandon(_ id: UUID) {
        didFinish(id)
    }

    package func shutdown() async {
        acceptsTransactions = false
        guard !active.isEmpty else { return }
        await withCheckedContinuation { continuation in
            if active.isEmpty {
                continuation.resume()
            } else {
                shutdownWaiters.append(continuation)
            }
        }
    }

    private func didFinish(_ id: UUID) {
        pending[id] = nil
        active.remove(id)
        guard active.isEmpty else { return }
        let waiters = shutdownWaiters
        shutdownWaiters.removeAll()
        for waiter in waiters {
            waiter.resume()
        }
    }
}
